let variantSeq = 0;

function variants(labels: string[], stock = 12): ProductVariant[] {
  return labels.map((label, i) => ({
    id: `v${++variantSeq}`,
    label,
    priceDelta: 0,
    stock: Math.max(1, stock - i),
    sku: `IB-${String(variantSeq).padStart(4, '0')}`,
  }));
}

let colorSeq = 0;

/** Colour is a separate axis from `variants` — a cardigan can have both
 * sizes and colours at once. `pairs` is [label, hex]. */
function colors(pairs: [string, string][], stock = 10): ColorOption[] {
  return pairs.map(([label, hex], i) => ({
    id: `col${++colorSeq}`,
    label,
    hex,
    stock: Math.max(1, stock - i * 2),
  }));
}

