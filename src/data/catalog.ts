    reviewCount: 12,
    stock: 20,
    isFeatured: false,
    isBestseller: false,
    careNotes: [],
    variants: [],
    colorOptions: [],
    // Overwritten below by DIMENSIONS_BY_SUBCATEGORY once every product
    // exists — this generic small-parcel default only matters as a type-safe
